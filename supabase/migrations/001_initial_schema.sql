CREATE OR REPLACE FUNCTION public.mi_rol()
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
  SELECT e.rol
  FROM public.empleados AS e
  WHERE e.auth_id = auth.uid()
    AND e.activo = TRUE
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.mi_empleado_id()
RETURNS UUID
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
  SELECT e.id
  FROM public.empleados AS e
  WHERE e.auth_id = auth.uid()
    AND e.activo = TRUE
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.es_administrador()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
  SELECT COALESCE(public.mi_rol() = 'Administrador', FALSE);
$$;

CREATE OR REPLACE FUNCTION public.es_gerente_o_administrador()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, auth, extensions
AS $$
  SELECT COALESCE(public.mi_rol() IN ('Gerente', 'Administrador'), FALSE);
$$;

-- ============================================================
-- ELIMINACION DE POLITICAS ANTERIORES
-- ============================================================

DO $$
DECLARE
  policy_record RECORD;
BEGIN
  FOR policy_record IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN (
        'empleados', 'productos_servicios', 'prospectos',
        'paquetes_tarifas', 'contratos', 'contrato_detalles',
        'agenda_eventos', 'seguimiento', 'pendientes', 'actividad_log'
      )
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      policy_record.policyname,
      policy_record.schemaname,
      policy_record.tablename
    );
  END LOOP;
END;
$$;

