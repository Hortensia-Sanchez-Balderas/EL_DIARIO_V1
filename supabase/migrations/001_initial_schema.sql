CREATE POLICY empleados_select_propio_gerente_admin
ON public.empleados FOR SELECT TO authenticated
USING (auth_id = auth.uid() OR public.mi_rol() IN ('Gerente', 'Administrador'));

CREATE POLICY empleados_insert_admin
ON public.empleados FOR INSERT TO authenticated
WITH CHECK (public.es_administrador());

CREATE POLICY empleados_update_admin
ON public.empleados FOR UPDATE TO authenticated
USING (public.es_administrador())
WITH CHECK (public.es_administrador());

CREATE POLICY empleados_delete_admin
ON public.empleados FOR DELETE TO authenticated
