CREATE TABLE IF NOT EXISTS public.empleados (
  id UUID PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  auth_id UUID NULL REFERENCES auth.users(id),
  nombre VARCHAR NOT NULL,
  email VARCHAR NOT NULL UNIQUE,
  rol VARCHAR NOT NULL
    CHECK (rol IN ('Vendedor', 'Gerente', 'Administrador')),
  fecha_contratacion DATE NULL,
  activo BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.productos_servicios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_servicio VARCHAR NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.prospectos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_empresa VARCHAR NOT NULL,
  nombre_contacto VARCHAR NOT NULL,
  cargo_contacto VARCHAR NULL,
  telefono VARCHAR NULL,
  email_contacto VARCHAR NULL,
  pagina_web VARCHAR NULL,
  domicilio TEXT NULL,
  estado VARCHAR NOT NULL DEFAULT 'Prospecto'
    CHECK (estado IN ('Prospecto', 'Cliente', 'Baja')),
  id_empleado_registro UUID NULL REFERENCES public.empleados(id),
  fecha_registro TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.paquetes_tarifas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_servicio INTEGER NOT NULL REFERENCES public.productos_servicios(id),
  pln VARCHAR NOT NULL,
  descripcion TEXT NULL,
  medidas_ejemplos VARCHAR NULL,
  tarifa_sin_iva NUMERIC NOT NULL
);

CREATE TABLE IF NOT EXISTS public.contratos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prospecto INTEGER NOT NULL REFERENCES public.prospectos(id),
  id_empleado_responsable UUID NOT NULL REFERENCES public.empleados(id),
  fecha_contrato DATE NOT NULL,
  fecha_inicio_publicacion DATE NULL,
  fecha_fin_publicacion DATE NULL,
  observaciones TEXT NULL,
  sub_total NUMERIC NULL,
  iva_monto NUMERIC NULL,
  total NUMERIC NOT NULL,
  estado VARCHAR NOT NULL DEFAULT 'Firmado'
    CHECK (estado IN ('Firmado', 'Vigente', 'Terminado', 'Cancelado')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.contrato_detalles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato INTEGER NOT NULL REFERENCES public.contratos(id),
  id_paquete INTEGER NOT NULL REFERENCES public.paquetes_tarifas(id),
  cantidad INTEGER NOT NULL,
  precio_unitario NUMERIC NOT NULL,
  importe NUMERIC NOT NULL
);

CREATE TABLE IF NOT EXISTS public.agenda_eventos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empleado UUID NOT NULL REFERENCES public.empleados(id),
  id_prospecto INTEGER NULL REFERENCES public.prospectos(id),
  titulo VARCHAR NOT NULL,
  descripcion TEXT NULL,
  fecha DATE NOT NULL,
  hora_inicio TIME NULL,
  hora_fin TIME NULL,
  tipo VARCHAR NOT NULL DEFAULT 'Otro'
    CHECK (tipo IN ('Llamada', 'Visita', 'Reunion', 'Seguimiento', 'Otro')),
  color VARCHAR DEFAULT '#008a52',
  completado BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.seguimiento (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prospecto INTEGER NOT NULL REFERENCES public.prospectos(id),
  id_empleado UUID NOT NULL REFERENCES public.empleados(id),
  tipo_accion VARCHAR NOT NULL,
  descripcion TEXT NULL,
  resultado TEXT NULL,
  fecha_accion TIMESTAMPTZ DEFAULT NOW(),
  proxima_accion DATE NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.pendientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empleado UUID NOT NULL REFERENCES public.empleados(id),
  id_prospecto INTEGER NULL REFERENCES public.prospectos(id),
  id_contrato INTEGER NULL REFERENCES public.contratos(id),
  titulo VARCHAR NOT NULL,
  descripcion TEXT NULL,
  prioridad VARCHAR NOT NULL DEFAULT 'Media'
    CHECK (prioridad IN ('Alta', 'Media', 'Baja')),
  completado BOOLEAN DEFAULT FALSE,
  fecha_limite DATE NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.actividad_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empleado UUID NOT NULL REFERENCES public.empleados(id),
  tipo_actividad VARCHAR NOT NULL,
  descripcion TEXT NULL,
  fecha_hora TIMESTAMPTZ DEFAULT NOW()
);

