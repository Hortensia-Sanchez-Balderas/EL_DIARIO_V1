CREATE TABLE IF NOT EXISTS public.contrato_archivos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato INTEGER NOT NULL REFERENCES public.contratos(id) ON DELETE CASCADE,
  formato VARCHAR NOT NULL CHECK (formato IN ('PDF', 'WORD', 'JPG')),
  nombre_archivo VARCHAR NOT NULL,
  ruta_storage TEXT NOT NULL,
  mime_type VARCHAR NOT NULL,
  tamano_bytes BIGINT NULL,
  id_empleado UUID NOT NULL REFERENCES public.empleados(id),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_contrato_archivos_id_contrato ON public.contrato_archivos(id_contrato);
CREATE INDEX IF NOT EXISTS idx_contrato_archivos_id_empleado ON public.contrato_archivos(id_empleado);

ALTER TABLE public.contrato_archivos ENABLE ROW LEVEL SECURITY;

CREATE POLICY contrato_archivos_select_propietario_gerente_admin
ON public.contrato_archivos FOR SELECT TO authenticated
USING (
  id_empleado = public.mi_empleado_id()
  OR public.es_gerente_o_administrador()
);

CREATE POLICY contrato_archivos_insert_vendedor
ON public.contrato_archivos FOR INSERT TO authenticated
WITH CHECK (
  id_empleado = public.mi_empleado_id()
  AND public.mi_rol() = 'Vendedor'
);

CREATE POLICY contrato_archivos_delete_vendedor_propietario
ON public.contrato_archivos FOR DELETE TO authenticated
USING (
  id_empleado = public.mi_empleado_id()
  AND public.mi_rol() = 'Vendedor'
);

GRANT SELECT, INSERT, DELETE ON public.contrato_archivos TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.contrato_archivos_id_seq TO authenticated;

INSERT INTO storage.buckets (id, name, public)
VALUES ('contratos', 'contratos', FALSE)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY storage_contratos_select
ON storage.objects FOR SELECT TO authenticated
USING (
  bucket_id = 'contratos'
  AND (
    public.es_gerente_o_administrador()
    OR EXISTS (
      SELECT 1 FROM public.contratos AS c
      WHERE c.id::text = (storage.foldername(name))[1]
        AND c.id_empleado_responsable = public.mi_empleado_id()
    )
  )
);

CREATE POLICY storage_contratos_insert
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'contratos'
  AND public.mi_rol() = 'Vendedor'
  AND EXISTS (
    SELECT 1 FROM public.contratos AS c
    WHERE c.id::text = (storage.foldername(name))[1]
      AND c.id_empleado_responsable = public.mi_empleado_id()
  )
);

CREATE POLICY storage_contratos_delete
ON storage.objects FOR DELETE TO authenticated
USING (
  bucket_id = 'contratos'
  AND public.mi_rol() = 'Vendedor'
  AND EXISTS (
    SELECT 1 FROM public.contratos AS c
    WHERE c.id::text = (storage.foldername(name))[1]
      AND c.id_empleado_responsable = public.mi_empleado_id()
  )
);
